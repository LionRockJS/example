-- Create tag schema
CREATE SCHEMA IF NOT EXISTS tag;
SET search_path TO tag, public;

CREATE TABLE tag.tag_types(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID UNIQUE DEFAULT uuidv7() NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    name TEXT UNIQUE NOT NULL
);

CREATE TRIGGER updated_at
    BEFORE UPDATE ON tag.tag_types
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at_timestamp();

CREATE TABLE tag.tags(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID UNIQUE DEFAULT uuidv7() NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    name TEXT UNIQUE NOT NULL,
    original TEXT,
    tag_type_id BIGINT,
    parent_tag BIGINT,
    FOREIGN KEY (tag_type_id) REFERENCES tag.tag_types (id) ON DELETE CASCADE,
    FOREIGN KEY (parent_tag) REFERENCES tag.tags (id) ON DELETE SET NULL
);

CREATE TRIGGER updated_at
    BEFORE UPDATE ON tag.tags
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at_timestamp();
